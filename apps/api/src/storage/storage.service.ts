import { GetObjectCommand, PutObjectCommand, S3Client } from '@aws-sdk/client-s3';
import { Inject, Injectable, Logger } from '@nestjs/common';
import { createReadStream } from 'node:fs';
import { mkdir, stat, writeFile } from 'node:fs/promises';
import { isAbsolute, join, resolve, sep } from 'node:path';
import { Readable } from 'node:stream';
import { ENV } from '../config/config.module';
import type { Env } from '../config/env';

export type StorageDriver = 's3' | 'local';

/** Thrown when an object that the database references is missing from storage. */
export class StoredObjectMissingError extends Error {
  constructor(key: string) {
    super(`Stored object not found: ${key}`);
  }
}

/**
 * Object storage abstraction. Uses S3-compatible storage (MinIO in dev) when every S3_* variable is set,
 * otherwise a local directory. Keys are generated by callers and must be opaque (e.g. `logos/<uuid>`).
 */
@Injectable()
export class StorageService {
  private readonly logger = new Logger(StorageService.name);
  readonly driver: StorageDriver;
  private readonly s3?: S3Client;
  private readonly bucket?: string;
  private readonly localRoot: string;

  constructor(@Inject(ENV) env: Env) {
    this.localRoot = isAbsolute(env.UPLOAD_DIR) ? env.UPLOAD_DIR : resolve(__dirname, '..', '..', env.UPLOAD_DIR);
    if (env.S3_ENDPOINT && env.S3_BUCKET && env.S3_ACCESS_KEY && env.S3_SECRET_KEY) {
      this.driver = 's3';
      this.bucket = env.S3_BUCKET;
      this.s3 = new S3Client({
        endpoint: env.S3_ENDPOINT,
        region: env.S3_REGION,
        forcePathStyle: env.S3_FORCE_PATH_STYLE,
        credentials: { accessKeyId: env.S3_ACCESS_KEY, secretAccessKey: env.S3_SECRET_KEY },
      });
    } else {
      this.driver = 'local';
    }
    this.logger.log(`Upload storage driver: ${this.driver}${this.driver === 'local' ? ` (${this.localRoot})` : ''}`);
  }

  async put(key: string, body: Buffer, contentType: string): Promise<void> {
    if (this.s3) {
      await this.s3.send(new PutObjectCommand({ Bucket: this.bucket, Key: key, Body: body, ContentType: contentType }));
      return;
    }
    const path = this.localPath(key);
    await mkdir(resolve(path, '..'), { recursive: true });
    // `wx` refuses to overwrite: keys are random so a collision indicates a bug.
    await writeFile(path, body, { flag: 'wx', mode: 0o600 });
  }

  async get(key: string): Promise<Readable> {
    if (this.s3) {
      try {
        const out = await this.s3.send(new GetObjectCommand({ Bucket: this.bucket, Key: key }));
        if (!out.Body) throw new StoredObjectMissingError(key);
        return out.Body as Readable;
      } catch (err) {
        if ((err as { name?: string }).name === 'NoSuchKey') throw new StoredObjectMissingError(key);
        throw err;
      }
    }
    const path = this.localPath(key);
    try {
      await stat(path);
    } catch {
      throw new StoredObjectMissingError(key);
    }
    return createReadStream(path);
  }

  /** Resolves a key inside the local root, refusing any path traversal. */
  private localPath(key: string): string {
    if (!/^[a-z0-9/_-]+$/i.test(key)) throw new Error(`Invalid storage key: ${key}`);
    const path = join(this.localRoot, key);
    if (!path.startsWith(this.localRoot + sep)) throw new Error(`Invalid storage key: ${key}`);
    return path;
  }
}
